function text(value: unknown, fallback = "Pending"): string {
  return typeof value === "string" && value.trim() ? value.trim() : fallback;
}

function dateText(value: string | null | undefined): string {
  return value ? value.slice(0, 10) : "Pending";
}

function normalizeAddressPart(value: string): string {
  return value
    .normalize("NFKD")
    .replace(/[^\x00-\x7F]/g, "")
    .replace(/\s+/g, " ")
    .replace(/[.,]+$/g, "")
    .trim()
    .toLowerCase();
}

export function buildHygieneSiteLabel(site: HygieneSite): string {
  const parts = [site.siteName, site.address];
  const addressKey = normalizeAddressPart(site.address);

  for (const value of [site.suburb, site.city]) {
    const key = normalizeAddressPart(value);
    if (key && !addressKey.includes(key)) parts.push(value);
  }

  return parts.filter((value) => typeof value === "string" && value.trim()).join(", ");
}

function slug(value: string): string {
  const cleaned = text(value, "Pending")
    .normalize("NFKD")
    .replace(/[^\x00-\x7F]/g, "")
    .replace(/[^a-zA-Z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80);
  return cleaned || "Pending";
}

