function drawText(page: PDFPage, value: string, x: number, y: number, options: { size?: number; font: PDFFont; color?: ReturnType<typeof rgb>; maxWidth?: number }) {
  page.drawText(value, { x, y, size: options.size ?? 10, font: options.font, color: options.color ?? NAVY, maxWidth: options.maxWidth });
}

function wrapText(value: string, font: PDFFont, size: number, maxWidth: number): string[] {
  const lines: string[] = [];
  for (const paragraph of text(value).split(/\r?\n/)) {
    const words = paragraph.split(/\s+/).filter(Boolean);
    let line = "";
    for (const word of words) {
      const candidate = line ? line + " " + word : word;
      if (font.widthOfTextAtSize(candidate, size) <= maxWidth) {
        line = candidate;
        continue;
      }
      if (line) lines.push(line);
      if (font.widthOfTextAtSize(word, size) <= maxWidth) {
        line = word;
        continue;
      }
      let fragment = "";
      for (const char of word) {
        const candidateFragment = fragment + char;
        if (font.widthOfTextAtSize(candidateFragment, size) <= maxWidth) {
          fragment = candidateFragment;
        } else {
          if (fragment) lines.push(fragment);
          fragment = char;
        }
      }
      line = fragment;
    }
    lines.push(line || " ");
  }
  return lines;
}

function wrappedTextHeight(value: string, font: PDFFont, size: number, maxWidth: number): number {
  return wrapText(value, font, size, maxWidth).length * size * LINE_HEIGHT_FACTOR;
}

function drawWrappedText(page: PDFPage, value: string, x: number, y: number, options: { size: number; font: PDFFont; color?: ReturnType<typeof rgb>; maxWidth: number }) {
  const lineHeight = options.size * LINE_HEIGHT_FACTOR;
  const lines = wrapText(value, options.font, options.size, options.maxWidth);
  lines.forEach((line, index) => {
    drawText(page, line, x, y - index * lineHeight, { font: options.font, size: options.size, color: options.color, maxWidth: options.maxWidth });
  });
  return lines.length * lineHeight;
}

