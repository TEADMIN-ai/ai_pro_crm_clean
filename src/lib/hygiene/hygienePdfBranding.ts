export function measureHygienePdfRowsForTesting(rows: Array<[string, string]>, width: number, fonts: { regular: PDFFont; bold: PDFFont }) {
  const labelWidth = width * 0.32;
  const valueWidth = width - labelWidth - ROW_PADDING_X * 3;
  return rows.map(([label, value]) => {
    const labelHeight = wrappedTextHeight(label, fonts.bold, 8, labelWidth - ROW_PADDING_X * 2);
    const valueHeight = wrappedTextHeight(value, fonts.regular, 8.2, valueWidth - ROW_PADDING_X * 2);
    return Math.max(20, Math.ceil(Math.max(labelHeight, valueHeight) + ROW_PADDING_Y * 2));
  });
}

function drawRows(page: PDFPage, kit: PdfKit, rows: Array<[string, string]>, x: number, y: number, width: number) {
  let cursor = y;
  const labelWidth = width * 0.32;
  const valueX = x + labelWidth + ROW_PADDING_X;
  const valueWidth = width - labelWidth - ROW_PADDING_X;
  const heights = measureHygienePdfRowsForTesting(rows, width, kit.fonts);
  for (const [index, [label, value]] of rows.entries()) {
    const rowHeight = heights[index] ?? 26;
    page.drawRectangle({ x, y: cursor - rowHeight + 9, width, height: rowHeight, borderColor: BORDER, borderWidth: 0.35 });
    const textY = cursor - ROW_PADDING_Y;
    drawWrappedText(page, label, x + ROW_PADDING_X, textY, { font: kit.fonts.bold, size: 8, color: MUTED, maxWidth: labelWidth - ROW_PADDING_X * 2 });
    drawWrappedText(page, value, valueX + ROW_PADDING_X, textY, { font: kit.fonts.regular, size: 8.2, color: NAVY, maxWidth: valueWidth - ROW_PADDING_X * 2 });
    cursor -= rowHeight;
  }
  return cursor;
}

function requiredRowsHeight(rows: Array<[string, string]>, width: number, fonts: { regular: PDFFont; bold: PDFFont }) {
  return measureHygienePdfRowsForTesting(rows, width, fonts).reduce((total, height) => total + height, 0);
}

function publicSignatureRows(signatures: HygieneSignature[] | undefined): Array<[string, string]> {
  if (!signatures?.length) return [["Client representative", "Pending"], ["Signature date", "Pending"]];
  return signatures.map((signature) => [`${signature.representativeName} (${signature.representativePosition})`, dateText(signature.capturedAt)]);
}

function publicCertificateSummary(evidence: Array<HygieneEvidencePhoto | HygieneComplianceDocument> | undefined, manifest: HygieneManifest): string {
  if (manifest.disposalCertificateNo && !/pending/i.test(manifest.disposalCertificateNo)) return manifest.disposalCertificateNo;
  const certificate = evidence?.find((item) => "category" in item ? item.category === "Disposal Certificate" : item.documentType === "Disposal Certificates");
  return certificate ? "Certificate evidence attached" : "Certificate evidence not available yet";
}

export function assertClientFacingHygienePdfContent(markers: string[]) {
  const combined = markers.join("\n").toLowerCase();
  const leaked = INTERNAL_LABELS.find((label) => combined.includes(label));
  if (leaked) throw new Error(`Client-facing Hygiene PDF contains restricted internal marker: ${leaked}`);
}

function ensureBodySpace(kit: PdfKit, currentPage: PDFPage, y: number, title: string, subtitle: string, requiredHeight: number) {
  if (y - requiredHeight >= BODY_BOTTOM) return { page: currentPage, y };
  return { page: addPage(kit, title, subtitle), y: BODY_TOP };
}

function drawRowsSection(kit: PdfKit, page: PDFPage, heading: string, rows: Array<[string, string]>, y: number, title: string, subtitle: string) {
  const width = PAGE_WIDTH - MARGIN * 2;
  const requiredHeight = 18 + 8 + requiredRowsHeight(rows, width, kit.fonts);
  const ready = ensureBodySpace(kit, page, y, title, subtitle, requiredHeight);
  drawSection(ready.page, kit, heading, ready.y);
  const nextY = drawRows(ready.page, kit, rows, MARGIN, ready.y - 18, width) - 6;
  return { page: ready.page, y: nextY };
}

